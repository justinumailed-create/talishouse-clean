import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { systemMapsiteOpeningZoom } from "../lib/talispros/system-mapsite-zoom";
import {
  isOwnerOnlyPersonalHomeHref,
  isSystemFastCodeActor,
  personalHomeFlagFrame,
  restrictSystemFastCodeFeatures,
  stepPersonalHomeMapZoom,
} from "../lib/talispros/system-fast-code-gate";

const read = (path: string) => readFileSync(join(process.cwd(), path), "utf8");

describe("system FAST Code feature gate", () => {
  it("treats daily-job and system assignment as the flag, not an eBook autoGenerated mark", () => {
    expect(isSystemFastCodeActor("system")).toBe(true);
    expect(isSystemFastCodeActor(" daily-job ")).toBe(true);
    expect(isSystemFastCodeActor("Aritri")).toBe(false);
    expect(isSystemFastCodeActor("autoGenerated")).toBe(false);
    expect(isSystemFastCodeActor(null)).toBe(false);
  });

  it("hides owner features only for an unclaimed system code seen by a broker", () => {
    expect(
      restrictSystemFastCodeFeatures({
        systemGenerated: true,
        registeredOrClaimed: false,
        agentAccess: false,
      }),
    ).toBe(true);
    expect(
      restrictSystemFastCodeFeatures({
        systemGenerated: true,
        registeredOrClaimed: true,
        agentAccess: false,
      }),
    ).toBe(false);
    expect(
      restrictSystemFastCodeFeatures({
        systemGenerated: true,
        registeredOrClaimed: false,
        agentAccess: true,
      }),
    ).toBe(false);
    expect(
      restrictSystemFastCodeFeatures({
        systemGenerated: false,
        registeredOrClaimed: false,
        agentAccess: false,
      }),
    ).toBe(false);
  });

  it("drops dashboard, editor, and password-gate links from the public home", () => {
    expect(isOwnerOnlyPersonalHomeHref("/talispros/mapsite/brokers/dw01")).toBe(true);
    expect(isOwnerOnlyPersonalHomeHref("/talispros/demo-mapsite?gate=dw01")).toBe(true);
    expect(isOwnerOnlyPersonalHomeHref("/talispros/mapsites/dw01/ebooks/new")).toBe(true);
    expect(isOwnerOnlyPersonalHomeHref("/chat")).toBe(true);
    expect(isOwnerOnlyPersonalHomeHref("/talispros/markets/claim-a-market")).toBe(false);
    expect(isOwnerOnlyPersonalHomeHref("/talisbooks/viewer/dw01-the-right-choice-realty-89dt")).toBe(
      false,
    );
    expect(isOwnerOnlyPersonalHomeHref("https://therightchoicerealty.ca/")).toBe(false);
  });

  it("opens near 80 km and can zoom in to building level", () => {
    const opening = systemMapsiteOpeningZoom(45.974, 640);
    expect(opening).not.toBe(17);
    expect(opening).not.toBe(12);
    expect(opening).toBeGreaterThanOrEqual(8);
    expect(opening).toBeLessThanOrEqual(11);
    let zoom = opening;
    for (let step = 0; step < 20; step += 1) zoom = stepPersonalHomeMapZoom(zoom, 1);
    expect(zoom).toBeGreaterThanOrEqual(18);
    expect(zoom).toBeLessThanOrEqual(20);
    expect(stepPersonalHomeMapZoom(3, -1)).toBe(3);
  });

  it("keeps the flag clear of the top-right zoom buttons", () => {
    for (const [width, height] of [
      [390, 640],
      [680, 800],
      [1280, 800],
    ] as const) {
      const frame = personalHomeFlagFrame(width, height);
      expect(frame.centerX + frame.width / 2).toBeLessThanOrEqual(width - 72);
      expect(frame.centerX - frame.width / 2).toBeGreaterThanOrEqual(0);
      expect(frame.top).toBeGreaterThanOrEqual(48);
      expect(frame.height).toBeGreaterThan(0);
    }
  });

  it("gates owner APIs and shows the existing map on the public home", () => {
    const page = read("app/talispros/home/[fastCode]/page.tsx");
    expect(page).toContain("isPublicSystemFastCode");
    expect(page).toContain("PersonalHomeMapsite");
    expect(page).toContain("isOwnerOnlyPersonalHomeHref");
    expect(page).toContain('id="mapsite"');
    const map = read("components/talispros/personal-home/PersonalHomeMapsite.tsx");
    expect(map).toContain("MapEngineCanvas");
    expect(map).toContain("MapSitePropertyPopup");
    expect(map).toContain('data-map-opening="80km"');
    expect(map).toContain("mapsite-zoom-in");
    expect(map).toContain("mapsite-zoom-out");
    expect(map).not.toContain("MapSitePinDashboard");
    expect(map).not.toContain("MapSiteStartHereOverlay");
    expect(map).not.toContain("TalisUMktsHeader");
    const auth = read("lib/mapsite-edit-auth.ts");
    expect(auth).toContain("isPublicSystemFastCode");
    expect(read("app/talispros/mapsites/actions.ts")).toContain("isPublicSystemFastCode");
    expect(read("app/talispros/mapsite/pin-actions.ts")).toContain("canManageMapSitePins");
    expect(read("lib/mapsite-edit-auth.ts")).toContain("canOwnerManage");
    expect(read("app/talispros/demo-mapsite/assign-actions.ts")).toContain("isPublicSystemFastCode");
    expect(read("lib/talispros/personal-home-page.ts")).toContain("isPublicSystemFastCode");
    const mapsitePage = read("app/talispros/mapsite/[accountType]/[fastCode]/page.tsx");
    expect(mapsitePage).toContain("hasProspectAccess()");
    expect(mapsitePage).toContain("isPreparedSlotMapsite");
  });
});
